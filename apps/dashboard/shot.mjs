import { chromium } from "@playwright/test";
import { createHash } from "node:crypto";
const session = createHash("sha256").update("pw:admin").digest("hex").slice(0, 16);
const [url, prefix, w, step] = process.argv.slice(2);
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: Number(w || 1400), height: 900 } });
await ctx.addCookies([{ name: "admin", value: session, domain: "localhost", path: "/" }]);
const p = await ctx.newPage();
await p.goto(url);
await p.waitForTimeout(7000);
const h = await p.evaluate(() => document.body.scrollHeight);
const s = Number(step || 2200);
let i = 0;
for (let y = 0; y < h; y += s, i++) await p.screenshot({ path: `${prefix}-${String(i).padStart(2, "0")}.png`, fullPage: true, clip: { x: 0, y, width: Number(w || 1400), height: Math.min(s, h - y) } });
const heads = await p.evaluate(() => [...document.querySelectorAll("h1,h2,h3")].map((e) => Math.round(e.getBoundingClientRect().top + scrollY) + " " + e.tagName + " " + e.textContent.trim().slice(0, 60)));
console.log("height", h, "slices", i); console.log(heads.join("\n"));
await b.close();
